#!/usr/bin/env bash
# Configures the Solace Cloud broker (created by ../terraform/) for the
# Zerobus ingest demo through the broker's own SEMP v2 Config API -- the
# cloud twin of local-broker/semp/configure-local-broker.sh:
#   - client profile allowing guaranteed messaging
#   - dead message queue (DMQ) and the ingest queue wired to it
#   - a publisher client username (publish-only ACL, for demo-apps/)
#   - a consumer client username for the Cloud-Managed Micro-Integration
#
# Uses the broker's manager credential from the Terraform output
# (../../output/service.json, written by ./show-service-connection.sh),
# NOT the Mission Control API token: SEMP and Mission Control are two
# separate authentication systems. Host and ports come from
# ../../output/service-endpoints.json (./get-service-endpoints.sh).
#
# Client usernames get generated passwords, kept in
# ../../output/cloud-broker.env (git-ignored, mode 600) and reused on
# re-runs. The script is idempotent: existing objects are skipped, and the
# user passwords are set to the stored values every time.
#
# Usage: ./configure-cloud-broker.sh
# Requires: curl, jq, openssl, and the two JSON files above.

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_DIR="${SCRIPT_DIR}/../../output"
SERVICE_JSON="${OUTPUT_DIR}/service.json"
ENDPOINTS_JSON="${OUTPUT_DIR}/service-endpoints.json"
CREDS_FILE="${OUTPUT_DIR}/cloud-broker.env"

for tool in curl jq openssl; do
  command -v "${tool}" >/dev/null 2>&1 || { echo "${tool} is required." >&2; exit 1; }
done
for f in "${SERVICE_JSON}" "${ENDPOINTS_JSON}"; do
  [[ -f "${f}" ]] || { echo "Missing ${f}. Run show-service-connection.sh and get-service-endpoints.sh first." >&2; exit 1; }
done

VPN="$(jq -r '.message_vpn.name' "${SERVICE_JSON}")"
ADMIN_USER="$(jq -r '.message_vpn.manager_management_credential.username' "${SERVICE_JSON}")"
ADMIN_PASSWORD="$(jq -r '.message_vpn.manager_management_credential.password' "${SERVICE_JSON}")"
HOST="$(jq -r '.data.defaultManagementHostname' "${ENDPOINTS_JSON}")"
SEMP_PORT="$(jq -r '[.data.serviceConnectionEndpoints[0].ports[] | select(.protocol=="serviceManagementTlsListenPort") | .port][0]' "${ENDPOINTS_JSON}")"
SMF_PORT="$(jq -r '[.data.serviceConnectionEndpoints[0].ports[] | select(.protocol=="serviceSmfTlsListenPort") | .port][0]' "${ENDPOINTS_JSON}")"
SEMP="https://${HOST}:${SEMP_PORT}/SEMP/v2/config"

QUEUE="${ZEROBUS_QUEUE_NAME:-q-zerobus-ingest}"
DMQ="dmq-${QUEUE#q-}"
TOPIC="${ZEROBUS_TOPIC_SUBSCRIPTION:-zerobus-demo/sensor/>}"
CLIENT_PROFILE="cp-zerobus"
PUBLISHER="pub-zerobus"
CONSUMER="sub-zerobus"

# Generated passwords: reuse the stored ones, create them on first run.
if [[ -f "${CREDS_FILE}" ]]; then
  # shellcheck disable=SC1090
  source "${CREDS_FILE}"
fi
if [[ -z "${CLOUD_PUBLISHER_PASSWORD:-}" || -z "${CLOUD_CONSUMER_PASSWORD:-}" ]]; then
  CLOUD_PUBLISHER_PASSWORD="$(openssl rand -hex 16)"
  CLOUD_CONSUMER_PASSWORD="$(openssl rand -hex 16)"
fi
(
  umask 077
  cat > "${CREDS_FILE}" <<CREDS
# Generated by configure-cloud-broker.sh. Git-ignored; keep it local.
CLOUD_SMF_HOST=tcps://${HOST}:${SMF_PORT}
CLOUD_MSG_VPN=${VPN}
CLOUD_QUEUE_NAME=${QUEUE}
CLOUD_DMQ_NAME=${DMQ}
CLOUD_PUBLISHER_USER=${PUBLISHER}
CLOUD_PUBLISHER_PASSWORD=${CLOUD_PUBLISHER_PASSWORD}
CLOUD_CONSUMER_USER=${CONSUMER}
CLOUD_CONSUMER_PASSWORD=${CLOUD_CONSUMER_PASSWORD}
CREDS
)

semp() {
  # semp METHOD PATH [JSON_BODY]
  local method="$1" path="$2" body="${3:-}"
  local args=(-sS -X "${method}" -u "${ADMIN_USER}:${ADMIN_PASSWORD}" -H "content-type: application/json" "${SEMP}${path}")
  [[ -n "${body}" ]] && args+=(-d "${body}")
  local response
  response="$(curl "${args[@]}")"
  if echo "${response}" | grep -q '"code"'; then
    if echo "${response}" | grep -q '"code": *6001' || echo "${response}" | grep -q '"status": *"ALREADY_EXISTS"'; then
      echo "  (already exists, skipping) ${path}"
    else
      echo "  WARN on ${method} ${path}:"
      echo "${response}"
    fi
  fi
}

echo "== Broker ${HOST}:${SEMP_PORT}, VPN '${VPN}' =="
echo "-- connectivity check --"
curl -sS -o /dev/null -w "SEMP reachable: HTTP %{http_code}\n" -u "${ADMIN_USER}:${ADMIN_PASSWORD}" "${SEMP}/msgVpns/${VPN}?select=msgVpnName"

echo "== 1. Client profile '${CLIENT_PROFILE}' (guaranteed messaging) =="
semp POST "/msgVpns/${VPN}/clientProfiles" \
  "{\"clientProfileName\":\"${CLIENT_PROFILE}\",\"allowGuaranteedMsgSendEnabled\":true,\"allowGuaranteedMsgReceiveEnabled\":true,\"allowGuaranteedEndpointCreateEnabled\":true}"
semp PATCH "/msgVpns/${VPN}/clientProfiles/${CLIENT_PROFILE}" \
  '{"allowGuaranteedMsgSendEnabled":true,"allowGuaranteedMsgReceiveEnabled":true,"allowGuaranteedEndpointCreateEnabled":true}'

echo "== 2. Dead Message Queue '${DMQ}' =="
semp POST "/msgVpns/${VPN}/queues" \
  "{\"queueName\":\"${DMQ}\",\"accessType\":\"exclusive\",\"permission\":\"consume\",\"ingressEnabled\":true,\"egressEnabled\":true,\"maxMsgSpoolUsage\":500}"

echo "== 3. Ingest queue '${QUEUE}' (wired to the DMQ) =="
semp POST "/msgVpns/${VPN}/queues" \
  "{\"queueName\":\"${QUEUE}\",\"accessType\":\"exclusive\",\"permission\":\"consume\",\"ingressEnabled\":true,\"egressEnabled\":true,\"maxMsgSpoolUsage\":1500,\"deadMsgQueue\":\"${DMQ}\",\"maxRedeliveryCount\":3}"
semp POST "/msgVpns/${VPN}/queues/${QUEUE}/subscriptions" "{\"subscriptionTopic\":\"${TOPIC}\"}"
echo "  ${QUEUE} <- subscribed to ${TOPIC}, dead messages -> ${DMQ}"

make_acl() {
  # make_acl ACL_NAME -- deny-all ACL profile; the caller adds exceptions.
  local acl="$1"
  semp POST "/msgVpns/${VPN}/aclProfiles" \
    "{\"aclProfileName\":\"${acl}\",\"clientConnectDefaultAction\":\"allow\",\"publishTopicDefaultAction\":\"disallow\",\"subscribeTopicDefaultAction\":\"disallow\"}"
}

echo "== 4. Publisher '${PUBLISHER}' (publish-only on ${TOPIC}) =="
make_acl "acl-${PUBLISHER}"
semp POST "/msgVpns/${VPN}/aclProfiles/acl-${PUBLISHER}/publishTopicExceptions" \
  "{\"publishTopicExceptionSyntax\":\"smf\",\"publishTopicException\":\"${TOPIC}\"}"
semp POST "/msgVpns/${VPN}/clientUsernames" \
  "{\"clientUsername\":\"${PUBLISHER}\",\"password\":\"${CLOUD_PUBLISHER_PASSWORD}\",\"enabled\":true,\"aclProfileName\":\"acl-${PUBLISHER}\",\"clientProfileName\":\"${CLIENT_PROFILE}\"}"
semp PATCH "/msgVpns/${VPN}/clientUsernames/${PUBLISHER}" '{"enabled":false}'
semp PATCH "/msgVpns/${VPN}/clientUsernames/${PUBLISHER}" \
  "{\"password\":\"${CLOUD_PUBLISHER_PASSWORD}\",\"aclProfileName\":\"acl-${PUBLISHER}\",\"clientProfileName\":\"${CLIENT_PROFILE}\"}"
semp PATCH "/msgVpns/${VPN}/clientUsernames/${PUBLISHER}" '{"enabled":true}'

echo "== 5. Consumer '${CONSUMER}' for the Cloud-Managed Micro-Integration =="
make_acl "acl-${CONSUMER}"
semp POST "/msgVpns/${VPN}/clientUsernames" \
  "{\"clientUsername\":\"${CONSUMER}\",\"password\":\"${CLOUD_CONSUMER_PASSWORD}\",\"enabled\":true,\"aclProfileName\":\"acl-${CONSUMER}\",\"clientProfileName\":\"${CLIENT_PROFILE}\"}"
semp PATCH "/msgVpns/${VPN}/clientUsernames/${CONSUMER}" '{"enabled":false}'
semp PATCH "/msgVpns/${VPN}/clientUsernames/${CONSUMER}" \
  "{\"password\":\"${CLOUD_CONSUMER_PASSWORD}\",\"aclProfileName\":\"acl-${CONSUMER}\",\"clientProfileName\":\"${CLIENT_PROFILE}\"}"
semp PATCH "/msgVpns/${VPN}/clientUsernames/${CONSUMER}" '{"enabled":true}'

echo "== 6. Trust store for TLS clients (demo-apps/publisher.py --target cloud) =="
# The broker's certificate chains up through Thawte TLS RSA CA G1 to the
# "DigiCert Global Root G2" (checked with openssl s_client on 17/10/2026);
# the truststore_uri in the service data points at an older DigiCert root,
# so both are downloaded. OpenSSL finds trusted certificates in a directory
# by hashed file name (<hash>.0), so each file also gets a copy under that name.
TRUST_DIR="${OUTPUT_DIR}/trust-store"
mkdir -p "${TRUST_DIR}"
TRUSTSTORE_URI="$(jq -r '.message_vpn.truststore_uri // empty' "${SERVICE_JSON}")"
for url in ${TRUSTSTORE_URI:+"${TRUSTSTORE_URI}"} "https://cacerts.digicert.com/DigiCertGlobalRootG2.crt.pem"; do
  curl -sS -o "${TRUST_DIR}/$(basename "${url}")" "${url}"
done
if command -v openssl >/dev/null 2>&1; then
  for pem in "${TRUST_DIR}"/*.pem; do
    cp -f "${pem}" "${TRUST_DIR}/$(openssl x509 -hash -noout -in "${pem}").0"
  done
else
  echo "  WARN: openssl not found, hashed copies not created"
fi
echo "  CA certificates saved in ${TRUST_DIR}/"

echo
echo "-- verification --"
for path in "queues/${QUEUE}?select=queueName,deadMsgQueue,maxRedeliveryCount" "queues/${DMQ}?select=queueName" \
            "clientUsernames/${PUBLISHER}?select=clientUsername,enabled,clientProfileName" \
            "clientUsernames/${CONSUMER}?select=clientUsername,enabled,clientProfileName"; do
  curl -sS -u "${ADMIN_USER}:${ADMIN_PASSWORD}" "${SEMP}/msgVpns/${VPN}/${path}" | jq -c '.data // .meta.error'
done

cat <<INFO

Done. Connection details and generated passwords are in
${CREDS_FILE} (git-ignored). Next: create and deploy the Cloud-Managed
Micro-Integration through the API.
INFO
